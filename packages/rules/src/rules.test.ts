import { describe, expect, it } from "vitest";
import { memoryRepo } from "@threadctx/discovery";
import { allowedMajors, exitCodeFor, grade, parseConfig, scan, stripInvisible, translateCommand, type Finding, type HistoryProvider } from "./index.js";

const NOW = new Date("2026-10-03T12:00:00Z");
const run = (files: Record<string, string>, opts: { history?: HistoryProvider; symlinks?: Record<string, string> } = {}) =>
  scan(memoryRepo(files, opts.symlinks), { now: NOW, history: opts.history });
const ids = (files: Record<string, string>, rule: string, opts?: Parameters<typeof run>[1]) =>
  run(files, opts).findings.filter((f) => f.ruleId === rule);
const pkg = (o: Record<string, unknown>) => JSON.stringify(o);

describe("structure", () => {
  it("S001 fires only when there is no context at all", () => {
    expect(ids({ "src/a.ts": "" }, "CTX-S001")).toHaveLength(1);
    expect(ids({ "AGENTS.md": "- hi" }, "CTX-S001")).toHaveLength(0);
  });

  it("S002 fires for isolated tool files and not when CLAUDE.md imports AGENTS.md", () => {
    const base = { "AGENTS.md": "- shared", ".cursor/rules/a.mdc": "---\nalwaysApply: true\n---\n- x" };
    expect(ids({ ...base, "CLAUDE.md": "- claude only" }, "CTX-S002")).toHaveLength(1);
    expect(ids({ ...base, "CLAUDE.md": "@AGENTS.md\n- extra" }, "CTX-S002")).toHaveLength(0);
    expect(ids({ "AGENTS.md": "x", "CLAUDE.md": "x" }, "CTX-S002", { symlinks: { "CLAUDE.md": "AGENTS.md" } })).toHaveLength(0);
  });

  it("S003 reports broken certain imports only", () => {
    const f = ids({ "CLAUDE.md": "@docs/missing.md\n@types/node is fine\nmail @example.com\n@./present.md", "present.md": "x" }, "CTX-S003");
    expect(f.map((x) => [x.line, x.evidence])).toEqual([[1, "@docs/missing.md"]]);
  });

  it("S004 reports globs that match nothing", () => {
    const files = {
      ".cursor/rules/a.mdc": "---\nglobs: \"**/*.vue\"\n---\n- vue",
      ".cursor/rules/b.mdc": "---\nglobs: \"*.ts\"\n---\n- ts",
      "src/x.ts": "",
    };
    const f = ids(files, "CTX-S004");
    expect(f.map((x) => [x.path, x.line])).toEqual([[".cursor/rules/a.mdc", 2]]);
  });

  it("S005 tolerates what tools read leniently but reports unreadable frontmatter and Copilot files without applyTo", () => {
    const f = ids({
      ".cursor/rules/lenient.mdc": "---\ndescription: x\nglobs: *.ts\n---\n- ts",
      ".claude/agents/a.md": "---\nname: a\ndescription: Use when: the user asks. Example: x\n---\nbody",
      ".cursor/rules/broken.mdc": "---\n[[[\n---\n- x",
      ".github/instructions/a.instructions.md": "- no frontmatter",
      "src/a.ts": "",
    }, "CTX-S005");
    expect(f.map((x) => x.path).sort()).toEqual([".cursor/rules/broken.mdc", ".github/instructions/a.instructions.md"]);
  });

  it("models lenient frontmatter: unquoted globs still apply", () => {
    const r = run({ ".cursor/rules/a.mdc": "---\nglobs: *.vue\n---\n- vue", "src/x.ts": "" });
    expect(r.findings.filter((x) => x.ruleId === "CTX-S004").map((x) => x.evidence)).toEqual(["*.vue"]);
  });

  it("S006 flags .cursorrules", () => {
    expect(ids({ ".cursorrules": "x" }, "CTX-S006")).toHaveLength(1);
  });
});

describe("drift", () => {
  it("D001 flags dead paths but tolerates abbreviations, examples, prohibitions and untracked conventions", () => {
    const files = {
      "AGENTS.md": [
        "- Entry point is `src/main.ts`.",
        "- Components live in `components/Button.tsx`.",
        "- Config: see `docs/setup.md`.",
        "- e.g. `src/feature/new.ts`",
        "- Never create `legacy/`.",
        "- Put secrets in `.env.local`.",
        "- Read [the guide](docs/guide.md).",
        "- Reports go to `docs/funnel-YYYY-MM-DD.md` and `src/{name}/index.ts`.",
        "- No `.github/copilot-instructions.md` file exists.",
        "- Core: `src/speech.h/.cpp`; add tests in `src/__tests__/ComponentName.spec.ts`.",
        "- `public/seed.sql` is regenerated by `pnpm seed`.",
      ].join("\n"),
      "src/index.ts": "",
      "src/components/Button.tsx": "",
      "docs/guide.md": "",
    };
    const f = ids(files, "CTX-D001");
    expect(f.map((x) => [x.line, x.message.includes("Did you mean")])).toEqual([[1, false], [3, false]]);
  });

  it("D001 skips gitignored paths and generator tables", () => {
    const f = ids({
      ".gitignore": "config/local.json\n",
      "AGENTS.md": "- Settings in `config/local.json`.\n| `docs/ref.md` | built by `scripts/generate-ref.mjs` |\n- See `config/missing.json`.",
      "config/example.json": "",
    }, "CTX-D001");
    expect(f.map((x) => x.line)).toEqual([3]);
  });

  it("D001 explains case-only mismatches that break on Linux", () => {
    const f = ids({ "AGENTS.md": "- See [security](docs/SECURITY.md).", "Docs/SECURITY.md": "" }, "CTX-D001");
    expect(f[0]!.message).toContain("only exists as `Docs/SECURITY.md`");
  });

  it("D001 suggests a unique same-name file", () => {
    const f = ids({ "AGENTS.md": "- See `lib/utils.ts`.", "src/shared/utils.ts": "" }, "CTX-D001");
    expect(f[0]!.message).toContain("src/shared/utils.ts");
    expect(f[0]!.fix?.edits[0]?.replacement).toBe("- See `src/shared/utils.ts`.");
  });

  it("D002 flags undefined scripts, accepts workspace scripts, bins and builtins", () => {
    const files = {
      "package.json": pkg({ scripts: { test: "vitest" }, devDependencies: { vitest: "1" } }),
      "apps/web/package.json": pkg({ scripts: { dev: "next dev" } }),
      "AGENTS.md": [
        "- `pnpm test`",
        "- `pnpm dev`",
        "- `pnpm run lint`",
        "- `pnpm vitest run`",
        "- `pnpm install`",
        "- `npm run typecheck`",
        "- `make build`",
      ].join("\n"),
    };
    const f = ids(files, "CTX-D002");
    expect(f.map((x) => x.line)).toEqual([3, 6, 7]);
  });

  it("D002 checks Makefile targets", () => {
    expect(ids({ Makefile: "test:\n\tgo test ./...\n", "AGENTS.md": "- `make test`\n- `make lint`" }, "CTX-D002").map((x) => x.line)).toEqual([2]);
  });

  it("D003 flags the wrong package manager with a safe fix, but not alternatives, globals or prohibitions", () => {
    const files = {
      "package.json": pkg({ scripts: { test: "vitest", build: "tsc" } }),
      "pnpm-lock.yaml": "",
      "AGENTS.md": [
        "- Run `npm run build` before committing.",
        "- Use yarn for everything.",
        "- Install the CLI globally: `npm i -g vercel`",
        "- Works with `npm test`, `pnpm test` or `yarn test`.",
        "- Never run `npm install`.",
        "- `pnpm test`",
      ].join("\n"),
    };
    const f = ids(files, "CTX-D003");
    expect(f.map((x) => x.line)).toEqual([1, 2]);
    expect(f[0]!.fix?.kind).toBe("safe");
    expect(f[0]!.fix?.edits[0]?.replacement).toBe("- Run `pnpm build` before committing.");
    expect(f[1]!.fix?.edits[0]?.replacement).toBe("- Use pnpm for everything.");
  });

  it("D003 stays quiet when lockfiles disagree", () => {
    expect(ids({ "pnpm-lock.yaml": "", "package-lock.json": "", "AGENTS.md": "- `npm install`" }, "CTX-D003")).toHaveLength(0);
  });

  it("D004 flags imports of packages the repo does not use", () => {
    const files = { "package.json": pkg({ dependencies: { zod: "3" } }), "AGENTS.md": "```ts\nimport { z } from \"zod\";\nimport axios from \"axios\";\nimport { x } from \"./local\";\nimport fs from \"node:fs\";\n```" };
    expect(ids(files, "CTX-D004").map((x) => x.evidence)).toEqual(['import axios from "axios";']);
  });

  it("D005 compares stated versions with engines, .nvmrc, python and deps; ignores lower bounds", () => {
    const files = {
      "package.json": pkg({ engines: { node: ">=20" }, dependencies: { react: "^18.2.0", next: "15.1.0" } }),
      "pyproject.toml": 'requires-python = ">=3.11"\n',
      "AGENTS.md": ["- Node 18", "- Node 22", "- Node 16+", "- React 17", "- React 18", "- Next.js 15", "- Python 3.10", "- Python 3.12"].join("\n"),
    };
    expect(ids(files, "CTX-D005").map((x) => x.line)).toEqual([1, 4, 7]);
  });

  it("allowedMajors parses common constraints", () => {
    expect(allowedMajors("^18.2.0")).toEqual({ exact: new Set([18]) });
    expect(allowedMajors(">=18 <21")).toEqual({ min: 18, max: 20 });
    expect(allowedMajors("lts/*")).toBeUndefined();
    expect(allowedMajors("^1 || ^2")).toBeUndefined();
  });

  it("D006 uses history when available", () => {
    const history: HistoryProvider = { lastCommitTime: () => 1000, commitsSince: () => 40 };
    const files = { "AGENTS.md": "- Code is in `src/`.", "src/a.ts": "" };
    expect(ids(files, "CTX-D006", { history })).toHaveLength(1);
    expect(ids(files, "CTX-D006")).toHaveLength(0);
  });
});

describe("conflict", () => {
  it("C001 finds package-manager and version conflicts across files", () => {
    const files = {
      "AGENTS.md": "- Install with `pnpm install`.\n- Node 20",
      "CLAUDE.md": "- Install with `npm install`.\n- Node 22",
      ".cursor/rules/a.mdc": "---\nalwaysApply: true\n---\n- Use pnpm.",
    };
    const f = ids(files, "CTX-C001");
    expect(f.map((x) => [x.path, x.message.split(":")[0]])).toEqual([
      ["CLAUDE.md", "Conflicting package manager"],
      ["CLAUDE.md", "Conflicting package manager"],
      ["CLAUDE.md", "Conflicting node version"],
    ]);
    expect(f[0]!.severity).toBe("blocker");
    expect(f.map((x) => x.related?.[0]?.path).sort()).toEqual([".cursor/rules/a.mdc", "AGENTS.md", "AGENTS.md"]);
  });

  it("C001 finds conflicting test runners through package.json scripts", () => {
    const files = {
      "package.json": pkg({ scripts: { test: "vitest run" } }),
      "AGENTS.md": "- Test: `pnpm test`",
      "CLAUDE.md": "- Test: `npx jest`",
    };
    expect(ids(files, "CTX-C001").map((x) => x.message.split(":")[0])).toEqual(["Conflicting test runner"]);
  });

  it("C001 ignores sibling monorepo packages that each have their own manifest", () => {
    const files = {
      "packages/a/package.json": pkg({ scripts: { test: "vitest" } }),
      "packages/b/package.json": pkg({ scripts: { test: "jest" } }),
      "packages/a/CLAUDE.md": "- Test: `pnpm test`",
      "packages/b/CLAUDE.md": "- Test: `pnpm test`",
    };
    expect(ids(files, "CTX-C001")).toHaveLength(0);
  });

  it("C001 does not treat equivalent commands or alternatives as conflicts", () => {
    const files = {
      "package.json": pkg({ scripts: { test: "vitest run" } }),
      "AGENTS.md": "- Test: `pnpm test`",
      "CLAUDE.md": "- Test: `pnpm vitest run`\n- Supports npm, pnpm or yarn: `npm i`, `pnpm i`, `yarn`",
    };
    expect(ids(files, "CTX-C001")).toHaveLength(0);
  });

  it("C003 flags nested overrides without their own manifest; C001 ignores nested pairs", () => {
    const files = { "AGENTS.md": "- Use pnpm.", "docs/AGENTS.md": "- Use npm.", "py/AGENTS.md": "- Use yarn.", "py/package.json": "{}" };
    expect(ids(files, "CTX-C003").map((x) => x.path)).toEqual(["docs/AGENTS.md"]);
    expect(ids(files, "CTX-C001").map((x) => x.path)).toEqual(["py/AGENTS.md"]);
  });

  it("C002 flags diverged copies of the same section", () => {
    const section = (extra: string) => `## Testing\n- Run unit tests first\n- Then integration tests\n- ${extra}\n`;
    expect(ids({ "AGENTS.md": section("Use fixtures"), "CLAUDE.md": section("Use mocks") }, "CTX-C002")).toHaveLength(1);
    expect(ids({ "AGENTS.md": section("Use fixtures"), "CLAUDE.md": "@AGENTS.md\n" + section("Use mocks") }, "CTX-C002")).toHaveLength(0);
    expect(ids({ "AGENTS.md": section("Same"), "CLAUDE.md": section("Same") }, "CTX-C002")).toHaveLength(0);
  });
});

describe("budget", () => {
  it("B001 reports tools over budget", () => {
    const big = "- " + "word ".repeat(6000);
    const f = ids({ "AGENTS.md": big }, "CTX-B001");
    expect(f).toHaveLength(1);
    expect(f[0]!.message).toMatch(/Claude Code ≈\d/);
    expect(f[0]!.message).toMatch(/Cursor ≈\d/);
  });

  it("B002 flags passages copied from the README", () => {
    const para = Array.from({ length: 50 }, (_, i) => `word${i}`).join(" ");
    expect(ids({ "README.md": `# X\n\n${para}\n`, "AGENTS.md": `${para}\n` }, "CTX-B002")).toHaveLength(1);
    expect(ids({ "README.md": "# X\n\nshort", "AGENTS.md": `${para}\n` }, "CTX-B002")).toHaveLength(0);
  });

  it("B003 needs three generic lines in one file", () => {
    const generic = "- Write clean code.\n- Follow best practices.\n- Use meaningful variable names.\n";
    expect(ids({ "AGENTS.md": generic }, "CTX-B003")).toHaveLength(1);
    expect(ids({ "AGENTS.md": "- Write clean code.\n- Run `pnpm test`." }, "CTX-B003")).toHaveLength(0);
  });

  it("B004 flags directives repeated across files", () => {
    const line = "- Always run the full test suite before opening a pull request please.";
    expect(ids({ "AGENTS.md": line, ".github/copilot-instructions.md": line }, "CTX-B004")).toHaveLength(1);
    expect(ids({ "AGENTS.md": line, ".github/copilot-instructions.md": "- Other." }, "CTX-B004")).toHaveLength(0);
    const block = [line, line.replace("pull", "merge"), line.replace("full", "whole")].join("\n");
    const grouped = ids({ "AGENTS.md": block, "CLAUDE.md": block }, "CTX-B004");
    expect(grouped).toHaveLength(1);
    expect(grouped[0]!.message).toMatch(/^3 directives repeat AGENTS.md/);
    // Path-scoped rules with disjoint globs never load together.
    const scoped = (g: string) => `---\nglobs: "${g}"\n---\n${block}`;
    expect(ids({ ".cursor/rules/a.mdc": scoped("*.ts"), ".cursor/rules/b.mdc": scoped("*.py"), "x.ts": "", "y.py": "" }, "CTX-B004")).toHaveLength(0);
    expect(ids({ ".cursor/rules/a.mdc": scoped("src/**"), ".cursor/rules/b.mdc": scoped("*.ts"), "src/x.ts": "" }, "CTX-B004")).toHaveLength(1);
    // Sibling subtrees never load together.
    expect(ids({ "agents/a/AGENTS.md": block, "agents/b/AGENTS.md": block }, "CTX-B004")).toHaveLength(0);
  });
});

