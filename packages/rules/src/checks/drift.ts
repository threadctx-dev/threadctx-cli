/** Paths conventionally absent from a clean checkout (generated, local, secret). */
const UNTRACKED_BY_CONVENTION = /(^|\/)(\.env(\.[\w.-]+)?|[^/]*\.local(\.[\w]+)?|node_modules|dist|build|out|coverage|\.next|\.nuxt|\.turbo|\.cache|target|venv|\.venv|__pycache__|tmp|\.vercel|\.terraform|_?generated|[^/]+\.log|[^/]+\.(db|sqlite3?|pyc)|compile_commands\.json)(\/|$)/;

/** Templates rather than paths: `docs/report-YYYY-MM-DD.md`, `src/{name}/index.ts`, `users/:id`. */
const PLACEHOLDER_PATH = /YYYY|(^|[^a-z])(MM|DD|HH|NNN|XXX|xxx)([^a-z]|$)|\{[^}]*\}|(^|\/):[a-z]|\bfoo\b|\bbar\b|\bmy-?(app|project|feature|component)\b/;

/** Lines describing deletions, renames, generated output, caches or future files are not claims of existence. */
const NOT_A_CLAIM = /\b(generat\w*|auto-generated|autogenerated|outputs?|cache[ds]?|ignored|gitignored?|deleted|removed|renamed|formerly|previously|legacy|no longer|does ?n[o']t exist|if (it )?exists|if present|optional(ly)?|create[sd]?|will be|should be|would be|new file|downloaded|runtime|at runtime|on the user's machine|in your home)\b|→|(?<!-)->|=>|regenerat\w*|删除|移除|已移除|如存在|例如|比如|示例|生成|新建|创建|如（|（如|作成|생성|예시|^\s*[-*]?\s*no\s|\bno\s+`[^`]+`\s+(file\s+)?(exists?|found)|\b(adding|add) one\b|\bin (the|our|a|their) [\w\s-]{0,30}\brepo(sitory)?\b/i;

/** Template names: ComponentName.spec.ts, your_tool.py, Xxx.vue, specs/spec_name/tasks.md. */
const TEMPLATE_NAME = /(Component|Widget|Feature|Module|Service|Class|Page|Screen|Hook|Store|Plugin|Tool|File|Project|Package|App)Name\b|\byour[_-]|\bmy[_-]|Your[A-Z]|\bXxx\b|\bxxx\b|[_-]name\b|\.\.\./;

/** Variants a reader would accept: `.js` imports of `.ts` sources, repo-name prefixes. */
function variants(value: string): string[] {
  const out = [value];
  const ts = value.match(/^(.*)\.(js|mjs|cjs|jsx)$/);
  if (ts) out.push(`${ts[1]}.ts`, `${ts[1]}.tsx`, `${ts[1]}.mts`, `${ts[1]}.cts`, `${ts[1]}.jsx`);
  const rest = value.split("/").slice(1).join("/");
  if (rest.includes("/")) out.push(rest);
  return out;
}

function pathExists(ctx: RuleContext, a: ParsedArtifact, claim: string): boolean {
  return variants(claim.replace(/\/+$/, "")).some((v) => pathExistsExact(ctx, a, v));
}

function pathExistsExact(ctx: RuleContext, a: ParsedArtifact, value: string): boolean {
  const candidates = new Set([value, joinRel(dirOf(a.artifact.path), value), joinRel(ownerDir(a.artifact.path) ?? "", value)]);
  for (const c of candidates) if (c !== undefined && (ctx.fs.exists(c) || ctx.fs.dirs.has(c))) return true;
  // People abbreviate: `components/Button.tsx` for `src/components/Button.tsx`.
  const suffix = `/${value}`;
  if (ctx.fs.files.some((f) => f.endsWith(suffix))) return true;
  for (const d of ctx.fs.dirs) if (d.endsWith(suffix)) return true;
  return false;
}

function joinRel(dir: string, p: string): string | undefined {
  const parts = (dir ? `${dir}/${p}` : p).split("/");
  const out: string[] = [];
  for (const part of parts) {
    if (part === "." || part === "") continue;
    if (part === "..") {
      if (!out.length) return undefined;
      out.pop();
    } else out.push(part);
  }
  return out.join("/");
}

const opaqueCache = new WeakMap<object, boolean>();
/** Repositories with git submodules: directories present in the tree with no files listed. */
function hasOpaqueDirs(ctx: RuleContext): boolean {
  const hit = opaqueCache.get(ctx.fs);
  if (hit !== undefined) return hit;
  const withFiles = new Set<string>();
  for (const f of ctx.fs.files) {
    const parts = f.split("/");
    for (let i = 1; i < parts.length; i++) withFiles.add(parts.slice(0, i).join("/"));
  }
  const result = [...ctx.fs.dirs].some((d) => d !== "" && !withFiles.has(d));
  opaqueCache.set(ctx.fs, result);
  return result;
}

/** True when the deepest existing ancestor directory has no listed files (submodule, ignored tree). */
function insideOpaqueDir(ctx: RuleContext, claim: string): boolean {
  const parts = claim.split("/");
  for (let i = parts.length - 1; i > 0; i--) {
    const dir = parts.slice(0, i).join("/");
    if (ctx.fs.dirs.has(dir)) return !ctx.fs.files.some((f) => f.startsWith(`${dir}/`) && !f.endsWith("/."));
  }
  return false;
}

function caseInsensitiveMatch(ctx: RuleContext, a: ParsedArtifact, claim: string): string | undefined {
  const lowers = [claim, joinRel(dirOf(a.artifact.path), claim)].filter((x): x is string => Boolean(x)).map((x) => x.toLowerCase());
  return ctx.fs.files.find((f) => lowers.includes(f.toLowerCase()));
}

function suggestPath(ctx: RuleContext, claim: string): string | undefined {
  const base = claim.replace(/\/+$/, "").split("/").pop()!;
  const hits = ctx.fs.files.filter((f) => f === base || f.endsWith(`/${base}`));
  return hits.length === 1 ? hits[0] : undefined;
}

function* claimsOf(ctx: RuleContext, type: Claim["type"]): Generator<{ a: ParsedArtifact; d: Directive; c: Claim }> {
  for (const a of ctx.artifacts) {
    if (!isOwnInstruction(a)) continue;
    for (const d of a.directives) for (const c of d.claims) if (c.type === type) yield { a, d, c };
  }
}

export const D001: Check = {
  ruleId: "CTX-D001",
  run(ctx, report) {
    for (const { a, d, c } of claimsOf(ctx, "path")) {
      if (d.kind === "prohibition" || isExampleContext(d)) continue;
      if (UNTRACKED_BY_CONVENTION.test(c.value) || PLACEHOLDER_PATH.test(c.value)) continue;
      // Precision: only file paths. Directories may be empty, ignored or created at runtime, and
      // slash-joined identifiers (`log/slog`, `async/await`, `piwi/fileSummary`) are not paths.
      // Bare file names are skipped unless linked: they are often runtime files or examples.
      const last = c.value.replace(/\/+$/, "").split("/").pop() ?? "";
      if (c.value.endsWith("/") || !FILE_EXT.test(last)) continue;
      if (c.value.includes("/.") || TEMPLATE_NAME.test(c.value)) continue; // `src/a.h/.cpp` shorthand, templates
      if (c.source !== "link" && c.value.startsWith("../")) continue; // relative to what is ambiguous outside links
      if (insideOpaqueDir(ctx, c.value)) continue; // git submodule or ignored tree: contents unknown
      if (ctx.facts.isIgnored(c.value) || ctx.facts.isIgnored(joinRel(dirOf(a.artifact.path), c.value) ?? "")) continue; // intentionally untracked
      if (hasOpaqueDirs(ctx) && !ctx.fs.dirs.has(c.value.split("/")[0]!) && !ctx.fs.dirs.has(joinRel(dirOf(a.artifact.path), c.value.split("/")[0]!) ?? "")) continue; // may live in a submodule
      if (new RegExp(`\\w's\\s+\`${c.value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`).test(lineText(a, c.line))) continue; // "classic's `x`": another codebase
      if (c.source !== "link" && !c.value.includes("/")) continue;
      if (/^[\w-]+(\.[\w-]+)*\.(com|org|net|io|dev|ai|app|co|so|me|xyz|cloud|sh|gg|us|eu|uk|de|fr|cn|jp)\//i.test(c.value)) continue; // module or URL without scheme
      if (c.value.startsWith("../") && !joinRel(dirOf(a.artifact.path), c.value)) continue;
      if (NOT_A_CLAIM.test(lineText(a, c.line))) continue;
      if (pathExists(ctx, a, c.value)) continue;
      const caseMatch = caseInsensitiveMatch(ctx, a, c.value);
      if (caseMatch) {
        report({
          path: a.artifact.path,
          line: c.line,
          message: `\`${c.value}\` only exists as \`${caseMatch}\`. That works on macOS and Windows but fails on Linux, where most CI and cloud agents run.`,
          evidence: quote(lineText(a, c.line)),
          fingerprintKey: c.value,
        });
        continue;
      }
      const suggestion = suggestPath(ctx, c.value);
      const line = lineText(a, c.line);
      report({
        path: a.artifact.path,
        line: c.line,
        message: suggestion
          ? `\`${c.value}\` does not exist. Did you mean \`${suggestion}\`?`
          : `\`${c.value}\` does not exist in the repository. Agents will follow a dead pointer.`,
        evidence: quote(line),
        fingerprintKey: c.value,
        fix: suggestion && line.includes(c.value)
          ? { kind: "suggested", description: `Point to ${suggestion}`, edits: [{ path: a.artifact.path, startLine: c.line, endLine: c.line, replacement: line.replace(c.value, suggestion) }] }
          : undefined,
      });
    }
  },
};

/** Executables commonly run through a package manager without a script ("pnpm vitest"). */
const COMMON_BINS = new Set(["tsc", "eslint", "prettier", "vitest", "jest", "next", "vite", "tsx", "ts-node", "playwright", "prisma", "drizzle-kit", "turbo", "nx", "changeset", "biome", "astro", "nuxt", "svelte-kit", "wrangler", "vercel", "netlify", "expo", "react-native", "storybook", "tailwindcss", "knip", "lint-staged", "husky", "rimraf", "concurrently", "nodemon", "cypress", "mocha", "c8", "nyc", "sb", "remix", "esbuild", "rollup", "webpack", "tsup", "unbuild", "jiti", "zx"]);

function scriptDefined(ctx: RuleContext, script: string): boolean {
  return ctx.facts.manifests.some((m) => script in m.scripts);
}

export const D002: Check = {
  ruleId: "CTX-D002",
  run(ctx, report) {
    const hasManifest = ctx.facts.manifests.length > 0;
    const hasMakefile = ctx.fs.files.some((f) => /(^|\/)(GNUmakefile|[Mm]akefile(\.[\w.-]+)?|CMakeLists\.txt|[^/]+\.(mk|make)|configure(\.ac)?|meson\.build)$/.test(f));
    const hasJustfile = ctx.fs.files.some((f) => /(^|\/)\.?justfile$|\.just$/i.test(f));
    for (const { a, d, c } of claimsOf(ctx, "command")) {
      if (d.kind === "prohibition" || isExampleContext(d)) continue;
      const raw = stripPrompt(c.value);
      const parsed = parseCommand(raw);
      if (!parsed.script || !parsed.scriptSource) continue;
      if (/[<>|*…{}\[\]]|\.\.\./.test(parsed.script) || /<[^>]+>/.test(raw)) continue; // placeholders: `<script>`, `dev:*`, `a|b`
      if (/[./]/.test(parsed.script) && parsed.scriptSource === "package.json" && /\.\w+$/.test(parsed.script)) continue; // `bun run file.ts`
      if (parsed.scriptSource === "Makefile" && /\s(-C|-f|--directory|--file|--makefile)\b/.test(raw)) continue; // another directory's Makefile
      // Explicit only when `run` is the first non-flag argument: `pnpm vitest run` runs a binary.
      const firstArg = raw.split(/\s+/).slice(1).find((t) => !t.startsWith("-"));
      const explicitRun = /^(npm|pnpm|yarn|bun)\b/.test(raw) && (firstArg === "run" || firstArg === "run-script");
      let missing = false;
      if (parsed.scriptSource === "package.json") {
        if (!hasManifest || scriptDefined(ctx, parsed.script)) continue;
        if (!explicitRun) {
          // `pnpm vitest` / `yarn eslint` run binaries when no script matches.
          if (COMMON_BINS.has(parsed.script) || ctx.facts.dependencyNames.has(parsed.script)) continue;
          if (parsed.tool === "npm") continue; // npm only runs scripts via run/test/start
        }
        missing = true;
      } else if (parsed.scriptSource === "Makefile") {
        if (!ctx.facts.makeTargets.has(parsed.script) && !hasMakefile) missing = true;
        else if (hasMakefile && ctx.facts.makeTargets.size > 0 && !ctx.facts.makeTargets.has(parsed.script) && !/[%$]/.test(parsed.script)) missing = true;
      } else if (parsed.scriptSource === "justfile") {
        missing = !hasJustfile || (ctx.facts.justRecipes.size > 0 && !ctx.facts.justRecipes.has(parsed.script));
      }
      if (!missing) continue;
      const where = parsed.scriptSource === "package.json" ? "any package.json" : parsed.scriptSource;
      report({
        path: a.artifact.path,
        line: c.line,
        message: `\`${normalizeCommand(raw)}\` runs \`${parsed.script}\`, which is not defined in ${where}. Agents will run a command that fails.`,
        evidence: quote(lineText(a, c.line)),
        fingerprintKey: normalizeCommand(raw),
      });
    }
  },
};

function expectedPackageManager(ctx: RuleContext): PackageManager | undefined {
  const rootLocks = new Set(ctx.facts.lockfiles.filter((l) => !l.path.includes("/")).map((l) => l.manager));
  if (ctx.facts.declaredPackageManager) {
    if (rootLocks.size === 0 || (rootLocks.size === 1 && rootLocks.has(ctx.facts.declaredPackageManager))) return ctx.facts.declaredPackageManager;
    return undefined; // packageManager field and lockfile disagree: not our call
  }
  return rootLocks.size === 1 ? [...rootLocks][0] : undefined;
}

/** Rewrite simple package-manager commands to another manager. Returns undefined when unsure. */
export function translateCommand(cmd: string, to: PackageManager): string | undefined {
  const tokens = normalizeCommand(cmd).split(" ");
  const from = tokens[0];
  if (!from || !["npm", "pnpm", "yarn", "bun"].includes(from)) return undefined;
  const rest = tokens.slice(1);
  if (rest.some((t) => t.startsWith("-"))) return undefined;
  const runScript = (s: string) => (to === "npm" ? (["test", "start"].includes(s) ? `npm ${s}` : `npm run ${s}`) : to === "bun" ? `bun run ${s}` : `${to} ${s}`);
  if (rest.length === 0 || (rest.length === 1 && ["install", "i"].includes(rest[0]!))) return `${to} install`;
  if (rest.length === 1 && rest[0] === "ci") return to === "npm" ? "npm ci" : `${to} install --frozen-lockfile`;
  if (rest[0] === "run" && rest.length === 2) return runScript(rest[1]!);
  if (rest.length === 1 && from !== "bun") {
    const builtin = parseCommand(`${from} ${rest[0]}`).script === undefined;
    if (!builtin) return runScript(rest[0]!);
  }
  return undefined;
}

