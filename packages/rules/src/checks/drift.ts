/** Majors allowed by a version constraint, or undefined if we cannot tell precisely. */
export function allowedMajors(constraint: string): { min?: number; max?: number; exact?: Set<number> } | undefined {
  const c = constraint.trim().replace(/^v/, "");
  if (!c || /^(lts|latest|node|stable|\*|x)/i.test(c) || c.includes("workspace:") || c.includes("||")) return undefined;
  const exact = c.match(/^[~^=]?\s*(\d+)(?:\.(?:\d+|x|\*))*(?:-[\w.]+)?$/);
  if (exact) return { exact: new Set([Number(exact[1])]) };
  const range = [...c.matchAll(/(>=|>|<=|<)\s*(\d+)(?:\.(\d+))?/g)];
  if (range.length && range.map((m) => m[0]).join(" ").replace(/\s+/g, "") === c.replace(/\s+/g, "").replace(/,/g, "")) {
    let min: number | undefined;
    let max: number | undefined;
    for (const m of range) {
      const n = Number(m[2]);
      const minor = Number(m[3] ?? 0);
      if (m[1] === ">=") min = n;
      else if (m[1] === ">") min = minor > 0 ? n : n + 1;
      else if (m[1] === "<") max = minor > 0 ? n : n - 1;
      else if (m[1] === "<=") max = n;
    }
    return { min, max };
  }
  return undefined;
}

function satisfies(major: number, allowed: NonNullable<ReturnType<typeof allowedMajors>>): boolean {
  if (allowed.exact) return allowed.exact.has(major);
  if (allowed.min !== undefined && major < allowed.min) return false;
  if (allowed.max !== undefined && major > allowed.max) return false;
  return true;
}

const DEP_PACKAGES: Record<string, string[]> = {
  react: ["react"], next: ["next"], typescript: ["typescript"], vue: ["vue"], angular: ["@angular/core"], svelte: ["svelte"],
  nuxt: ["nuxt"], express: ["express"], vite: ["vite"], tailwind: ["tailwindcss"], prisma: ["prisma", "@prisma/client"],
};

function pythonContradicts(stated: string, constraint: string): boolean | undefined {
  const s = stated.split(".").map(Number);
  if (s.length < 2 || s.some(Number.isNaN)) return undefined;
  const exact = constraint.match(/^(\d+)\.(\d+)(\.\d+)?$/);
  if (exact) return !(Number(exact[1]) === s[0] && Number(exact[2]) === s[1]);
  const ge = constraint.match(/^>=\s*(\d+)\.(\d+)(?:\.\d+)?$/);
  if (ge) return s[0]! < Number(ge[1]) || (s[0] === Number(ge[1]) && s[1]! < Number(ge[2]));
  return undefined;
}

export const D005: Check = {
  ruleId: "CTX-D005",
  run(ctx, report) {
    for (const a of ctx.artifacts) {
      if (!isOwnInstruction(a)) continue;
      for (const d of a.directives) {
        if (isExampleContext(d)) continue;
        for (const f of d.facts) {
          if (f.value.endsWith("+")) continue; // lower bound, not a contradiction candidate
          const lang = f.topicKey.match(/^lang\.(\w+)\.version$/)?.[1];
          const dep = f.topicKey.match(/^dep\.(\w+)\.version$/)?.[1];
          let actual: string | undefined;
          let source: string | undefined;
          // Docs state the supported floor; .nvmrc / .python-version pin the dev version. Compare
          // with the declared range when there is one, and fall back to pins only when not.
          const runtimes = (tool: string) => {
            const all = ctx.facts.runtimes.filter((x) => x.tool === tool);
            const ranges = all.filter((x) => /engines|requires-python/.test(x.source));
            return ranges.length ? ranges : all;
          };
          if (lang === "python") {
            for (const r of runtimes("python")) {
              if (pythonContradicts(f.value, r.constraint)) {
                actual = r.constraint;
                source = r.source;
                break;
              }
            }
          } else if (lang) {
            const major = Number(f.value);
            for (const r of runtimes(lang)) {
              const allowed = allowedMajors(r.constraint);
              if (allowed && !satisfies(major, allowed)) {
                actual = r.constraint;
                source = r.source;
                break;
              }
            }
          } else if (dep && DEP_PACKAGES[dep]) {
            const major = Number(f.value);
            const ranges = ctx.facts.manifests.flatMap((m) => DEP_PACKAGES[dep]!.filter((p) => m.dependencies[p]).map((p) => ({ range: m.dependencies[p]!, source: `${m.path} ${p}` })));
            const parsed = ranges.map((r) => ({ ...r, allowed: allowedMajors(r.range) }));
            if (parsed.length && parsed.every((p) => p.allowed && !satisfies(major, p.allowed))) {
              actual = parsed[0]!.range;
              source = parsed[0]!.source;
            }
          }
          if (!actual || !source) continue;
          const actualMajor = actual.match(/\d+(?:\.\d+)?/)?.[0];
          const line = lineText(a, f.line);
          const name = lang ?? dep!;
          report({
            path: a.artifact.path,
            line: f.line,
            message: `States ${name} ${f.value}, but ${source} requires ${actual}.`,
            evidence: quote(line),
            fingerprintKey: `${name}@${f.value}`,
            fix: actualMajor && lang !== "python" && !/[<>]/.test(actual)
              ? suggestVersionFix(a, f.line, line, f.value, actualMajor.split(".")[0]!)
              : undefined,
          });
        }
      }
    }
  },
};

function suggestVersionFix(a: ParsedArtifact, lineNo: number, line: string, stated: string, actual: string): Fix | undefined {
  const re = new RegExp(`(\\b[A-Za-z.]+\\s+v?)${stated.replace(".", "\\.")}(?![\\d.])`);
  if (!re.test(line)) return undefined;
  return { kind: "suggested", description: `State version ${actual}`, edits: [{ path: a.artifact.path, startLine: lineNo, endLine: lineNo, replacement: line.replace(re, `$1${actual}`) }] };
}

