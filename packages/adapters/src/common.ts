import { posix } from "node:path";
import picomatch from "picomatch";
import {
  artifactId, buildDirectives, contentHash, estimateTokens, extractImports, parseFrontmatter, sha256,
  stripBlockHtmlComments,
  type ArtifactKind, type ArtifactOrigin, type ContextArtifact, type Directive, type EffectiveContext,
  type EffectiveLayer, type Frontmatter, type FsView, type ImportRef, type LoadMode, type ToolId,
} from "@threadctx/core";

export interface ParsedArtifact {
  artifact: ContextArtifact;
  directives: Directive[];
  /** Raw file text. */
  text: string;
  frontmatter?: Frontmatter;
  imports: ImportRef[];
  /** Text an agent actually receives (frontmatter removed, comments stripped where the tool does). */
  loadedText: string;
  /** Repo-relative symlink target when the file is a symlink. */
  symlinkTarget?: string;
  /** True when the file was read outside the normal listing (e.g. gitignored CLAUDE.local.md). */
  untracked?: boolean;
}

export interface ArtifactSpec {
  tool: ToolId | "neutral";
  path: string;
  kind: ArtifactKind;
  origin?: ArtifactOrigin;
  /** Parse YAML frontmatter (rules, skills, subagents). */
  frontmatter: boolean;
  /** Strip block HTML comments from the loaded text (Claude Code behaviour). */
  stripComments?: boolean;
  /** Derive scope from frontmatter. */
  scope?: (fm: Frontmatter | undefined, path: string) => ContextArtifact["scope"];
  /** Tool-specific fields recorded on the artifact. */
  ext?: (fm: Frontmatter | undefined) => Record<string, unknown>;
  untracked?: boolean;
}

export function parseArtifact(fs: FsView, spec: ArtifactSpec): ParsedArtifact | undefined {
  const text = fs.readFile(spec.path);
  if (text === undefined) return undefined;
  const normalized = text.replace(/^﻿/, "").replace(/\r\n?/g, "\n");
  const fm = spec.frontmatter ? parseFrontmatter(normalized) : undefined;
  const body = fm ? fm.body : normalized;
  const bodyStartLine = fm ? fm.bodyStartLine : 1;
  const loadedText = spec.stripComments ? stripBlockHtmlComments(body) : body;
  const id = artifactId(spec.tool, spec.path);
  const dir = posix.dirname(spec.path) === "." ? "" : posix.dirname(spec.path);
  const scope = spec.scope ? spec.scope(fm, spec.path) : { directory: ownerDir(spec.path) ?? dir, alwaysApply: true };
  const artifact: ContextArtifact = {
    id,
    path: spec.path,
    tool: spec.tool,
    kind: spec.kind,
    origin: spec.origin ?? "repo",
    scope,
    contentHash: contentHash(normalized),
    tokenEstimate: estimateTokens(loadedText),
    ext: spec.ext ? spec.ext(fm) : {},
  };
  const generated = normalized.match(/^<!--\s*generated by threadctx from (\S+)/m);
  if (generated) artifact.generatedFrom = generated[1];
  return {
    artifact,
    directives: buildDirectives(id, body, bodyStartLine),
    text: normalized,
    frontmatter: fm,
    imports: extractImports(body, bodyStartLine),
    loadedText,
    symlinkTarget: fs.symlinkTarget(spec.path),
    untracked: spec.untracked,
  };
}

/** The directory an instruction file governs: `a/.claude/CLAUDE.md` governs `a`. */
export function ownerDir(path: string): string | undefined {
  const dir = posix.dirname(path);
  if (dir === ".") return "";
  const parts = dir.split("/");
  const toolDir = parts.findIndex((p) => p === ".claude" || p === ".cursor" || p === ".github" || p === ".gemini");
  if (toolDir !== -1) return parts.slice(0, toolDir).join("/");
  return dir;
}

/** Directories from the repo root down to (and including) `dir`. */
export function dirChain(dir: string): string[] {
  if (!dir) return [""];
  const parts = dir.split("/");
  return ["", ...parts.map((_, i) => parts.slice(0, i + 1).join("/"))];
}

export function dirOf(path: string): string {
  const d = posix.dirname(path);
  return d === "." ? "" : d;
}

export function join(dir: string, name: string): string {
  return dir ? `${dir}/${name}` : name;
}

/** Split a globs value that may be a comma-separated string or an array. */
export function globList(value: unknown): string[] {
  const raw = Array.isArray(value) ? value : typeof value === "string" ? splitCommaGlobs(value) : [];
  return raw.filter((v): v is string => typeof v === "string").map((v) => v.trim()).filter(Boolean);
}

/** Split on commas that are not inside a brace group, so `src/*.{ts,tsx}` stays whole. */
export function splitCommaGlobs(value: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let cur = "";
  for (const c of value) {
    if (c === "{") depth++;
    if (c === "}") depth = Math.max(0, depth - 1);
    if (c === "," && depth === 0) {
      out.push(cur);
      cur = "";
    } else cur += c;
  }
  out.push(cur);
  return out;
}

const matcherCache = new Map<string, (p: string) => boolean>();

/** Glob matcher. Patterns without a slash match the file name anywhere (gitignore-style). */
export function globMatcher(patterns: string[]): (path: string) => boolean {
  const key = patterns.join("\u0000");
  const cached = matcherCache.get(key);
  if (cached) return cached;
  const fns = patterns.map((p) => {
    const pattern = p.replace(/^\.\//, "").replace(/^\//, "");
    try {
      return picomatch(pattern, { dot: true, matchBase: !pattern.includes("/") });
    } catch {
      return () => false;
    }
  });
  const fn = (path: string) => fns.some((f) => f(path));
  matcherCache.set(key, fn);
  return fn;
}

export interface Target {
  /** Repo-relative path of a file, or a directory when `isDir`. */
  path: string;
  isDir: boolean;
}

/** Does a glob-scoped artifact apply to the target? For a directory, any file under it counts. */
export function targetMatches(fs: FsView, target: Target, patterns: string[]): boolean {
  const match = globMatcher(patterns);
  if (!target.isDir) return match(target.path);
  const prefix = target.path ? `${target.path}/` : "";
  return fs.files.some((f) => f.startsWith(prefix) && match(f));
}

export function targetDir(target: Target): string {
  return target.isDir ? target.path : dirOf(target.path);
}

/** Expand `@imports` breadth-first up to `maxHops`, returning existing imported files in load order. */
export function expandImports(
  fs: FsView,
  root: ParsedArtifact,
  parse: (path: string) => ParsedArtifact | undefined,
  maxHops: number,
): { artifact: ParsedArtifact; hops: number; via: string }[] {
  const out: { artifact: ParsedArtifact; hops: number; via: string }[] = [];
  const seen = new Set([root.artifact.path]);
  let frontier: { artifact: ParsedArtifact; hops: number }[] = [{ artifact: root, hops: 0 }];
  while (frontier.length) {
    const next: { artifact: ParsedArtifact; hops: number }[] = [];
    for (const { artifact, hops } of frontier) {
      if (hops >= maxHops) continue;
      for (const imp of artifact.imports) {
        const resolved = resolveImport(artifact.artifact.path, imp.path);
        if (!resolved || seen.has(resolved) || !fs.exists(resolved)) continue;
        const parsed = parse(resolved);
        if (!parsed) continue;
        seen.add(resolved);
        out.push({ artifact: parsed, hops: hops + 1, via: artifact.artifact.path });
        next.push({ artifact: parsed, hops: hops + 1 });
      }
    }
    frontier = next;
  }
  return out;
}

/** Resolve an import relative to the importing file. Returns undefined for paths outside the repo. */
export function resolveImport(fromPath: string, importPath: string): string | undefined {
  if (importPath.startsWith("~") || importPath.startsWith("/")) return undefined;
  const joined = posix.normalize(posix.join(dirOf(fromPath), importPath));
  if (joined.startsWith("..")) return undefined;
  return joined;
}

export class LayerBuilder {
  private layers: EffectiveLayer[] = [];
  private seen = new Set<string>();
  readonly notes: string[] = [];

  add(a: ParsedArtifact, loading: LoadMode, reason: string, tokenEstimate = a.artifact.tokenEstimate): void {
    if (this.seen.has(a.artifact.path)) return;
    this.seen.add(a.artifact.path);
    this.layers.push({ artifactId: a.artifact.id, path: a.artifact.path, precedence: this.layers.length + 1, loading, reason, tokenEstimate });
  }

  has(path: string): boolean {
    return this.seen.has(path);
  }

  build(tool: ToolId, target: Target, catalog: ReadonlyMap<string, ParsedArtifact>): EffectiveContext {
    const tokenEstimate = this.layers.reduce((n, l) => n + l.tokenEstimate, 0);
    const alwaysTokenEstimate = this.layers.filter((l) => l.loading === "always" || l.loading === "agent-decides").reduce((n, l) => n + l.tokenEstimate, 0);
    const hash = `sha256:${sha256(this.layers.map((l) => `${l.path}\u0000${catalog.get(l.path)?.artifact.contentHash ?? ""}\u0000${l.loading}`).join("\n"))}`;
    return { tool, targetPath: target.path, layers: this.layers, tokenEstimate, alwaysTokenEstimate, hash, notes: [...this.notes] };
  }
}
